  DELETEDBYRECEIVER tinyNUMBER(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (MESSAGEID),
  KEY SENDERUSERID (SENDERUSERID),
  KEY RECEIVERUSERID (RECEIVERUSERID),
  CONSTRANUMBER MESSAGES_IBFK_1 FOREIGN KEY (SENDERUSERID) REFERENCES USERS (USERID),
  CONSTRANUMBER MESSAGES_IBFK_2 FOREIGN KEY (RECEIVERUSERID) REFERENCES USERS (USERID)
) ;

